'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),parent=path.join(root,'outputs/entry-tests');
fs.mkdirSync(parent,{recursive:true});
const fixture=fs.mkdtempSync(path.join(parent,'run-'));
function write(name,data){const file=path.join(fixture,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,data);}
write('scripts/sync-entry-aliases.cjs',fs.readFileSync(path.join(root,'scripts/sync-entry-aliases.cjs')));
write('app/project-index/templates/index.html',fs.readFileSync(path.join(root,'app/project-index/templates/index.html')));
write('shared/config/channels.js',`window.__GAIP_CHANNEL_CONFIG__={list:[{key:'home',label:'首页',directory:'channels/home',entry:'channels/home/index.html',aliases:['导航文字别名']}],standaloneEntries:[{id:'login',directory:'channels/login',entry:'channels/login/index.html'},{id:'local',directory:'channels/local-test',entry:'channels/local-test/index.html',localOnly:true}]};`);
write('shared/config/project-structure.json','{"bundleMap":{}}');
write('channels/home/index.html','<html><body>Home</body></html>');
write('channels/login/index.html','<html><body>Login</body></html>');
const run=(...args)=>spawnSync(process.execPath,[path.join(fixture,'scripts/sync-entry-aliases.cjs'),...args],{encoding:'utf8'});
assert.equal(run().status,0);
assert.ok(!fs.existsSync(path.join(fixture,'home.html')));
assert.match(fs.readFileSync(path.join(fixture,'app/project-index/index.html'),'utf8'), /href="channels\/home\/index.html"/);
assert.ok(fs.existsSync(path.join(fixture,'index.html')));
assert.ok(!fs.existsSync(path.join(fixture,'导航文字别名')),'navigation aliases must never become filenames');
assert.ok(!fs.existsSync(path.join(fixture,'local.html')),'absent excluded experiments must not break a clean checkout');
assert.equal(run('--check').status,0);
assert.match(fs.readFileSync(path.join(fixture,'index.html'),'utf8'), /<body>Login<\/body>/);
write('channels/local-test/index.html','<html><body>Local</body></html>');
assert.equal(run().status,0);
assert.ok(!fs.existsSync(path.join(fixture,'local.html')),'local experiments do not create root aliases');
assert.equal(run('--check').status,0);
assert.match(fs.readFileSync(path.join(fixture,'index.html'),'utf8'), /<body>Login<\/body>/);
write('old.html','old');
assert.notEqual(run('--check').status,0,'stray root aliases must be reported');
fs.unlinkSync(path.join(fixture,'old.html'));
write('index.html','stale');
assert.notEqual(run('--check').status,0,'stale project directory must be reported');
console.log('PASS: canonical entries, generated project directory, no root aliases, and optional local experiments.');
